"""The libraries the importer builds, as values.

A Library names where one generated folder comes from (a 5e.tools data clone and,
for the 2024 library, the list of source ids it takes entries from) and how it is
written (folder, edition, marker text, Needs Review intro). The 2024 source list
is sources-2024.json: ids, kind, published date and enabled flag, no titles.
"""
import json
import os
from dataclasses import dataclass

from . import render

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES_2024 = os.path.normpath(os.path.join(HERE, "..", "sources-2024.json"))
CUTOFF_2024 = "2024-09-17"

# notes keep the plain name for the first of these that has the entity; later ones get "(SRC)"
PRIORITY_2014 = ("PHB", "DMG", "MM", "XGE", "TCE", "VGM", "MTF", "SCAG", "ERLW", "EGW", "GGR", "MOT", "VRGR",
                 "FTD", "SCC", "BGG", "BMT", "AAG", "BAM", "MPMM")

MARKER_2014 = ("Generated by scripts/dnd-compendium (5e.tools data). Replaced on every sync; "
               "keep your own notes outside this folder.\n")
MARKER_2024 = ("Generated by scripts/dnd-compendium (5e.tools 2024 data). Replaced on every sync; "
               "keep your own notes outside this folder.\n")
REVIEW_INTRO_2024 = ("Entries the converter could not read cleanly from the 2024 data. Each note's `needs_review` "
                     "property lists the problem; compare with the book and edit the note.")

MYSTIC_ARTS = "compendium/5e/Mystic Arts"  # built from another branch: counted, never built or synced here


@dataclass(frozen=True)
class Library:
    folder: str
    edition: str
    data_dir: str                      # clone directory under $DNDC_ROOT
    sources: "frozenset[str] | None"   # None: every source in the clone
    priority: "tuple[str, ...]"        # same-name entities: the first source here keeps the plain name
    marker_text: str
    review_intro: "str | None"         # None keeps the OCR sentence of the PDF route


def load_sources(path=SOURCES_2024):
    """Entries {id, kind, published, enabled}, in published order."""
    with open(path) as f:
        return json.load(f)["sources"]


def _priority_2024(entries):
    on = [e for e in entries if e["enabled"]]
    key = lambda e: (e["published"], e["id"])
    return tuple(e["id"] for kind in ("book", "adventure") for e in sorted(on, key=key) if e["kind"] == kind)


def _lib_2024():
    entries = load_sources()
    return Library(folder=f"{render.LIB} 2024", edition="2024", data_dir="5etools-2024",
                   sources=frozenset(e["id"] for e in entries if e["enabled"]),
                   priority=_priority_2024(entries), marker_text=MARKER_2024, review_intro=REVIEW_INTRO_2024)


WOTC_2014 = Library(folder=render.LIB, edition="2014", data_dir="5etools-2014", sources=None,
                    priority=PRIORITY_2014, marker_text=MARKER_2014, review_intro=None)
WOTC_2024 = _lib_2024()
BUILT = [WOTC_2014, WOTC_2024]

EDITIONS = {WOTC_2014.folder: "2014", WOTC_2024.folder: "2024"}
EDITIONS.update({folder: "2014" for folder in render.PUBLISHER_LIBS.values()})
SYNC_DEFAULT = list(render.LIBS)
_PREFIX = "compendium/5e/"


def _targets(names, default, allowed):
    if names is None:
        return list(default)
    out = []
    for n in names:
        folder = _PREFIX + n
        if n != n.strip() or folder not in allowed:
            raise SystemExit(f"unknown library {n!r}; choose from: {', '.join(f[len(_PREFIX):] for f in allowed)}")
        out.append(folder)
    return out


def sync_targets(names):
    """Full folders for names under compendium/5e/; None gives the default three. Anything else exits."""
    return _targets(names, SYNC_DEFAULT, EDITIONS)


def build_targets(names):
    """Same validation for build --libs; None builds every library this branch builds."""
    return _targets(names, [lib.folder for lib in BUILT] + list(render.PUBLISHER_LIBS.values()), EDITIONS)


def count_targets(names):
    """vault-count is read-only, so it may also look at Mystic Arts."""
    allowed = list(EDITIONS) + [MYSTIC_ARTS]
    return _targets(names, SYNC_DEFAULT + [WOTC_2024.folder, MYSTIC_ARTS], allowed)


def source_warnings(lib, books, adventures, cutoff=CUTOFF_2024, disabled=None):
    """Lines for a source list that disagrees with the clone; the build logs them and still runs.

    disabled: ids listed in the file with enabled false (default: read from the file); they are in
    the clone on purpose and never warned about.
    """
    if lib.sources is None:
        return []
    if disabled is None:
        disabled = {e["id"] for e in load_sources() if not e["enabled"]}
    listed = set(lib.sources) | disabled
    have = {x["id"] for x in list(books) + list(adventures)}
    out = []
    missing = sorted(lib.sources - have)
    if missing:
        out.append(f"listed in sources-2024.json but not in the clone: {', '.join(missing)}")
    new = sorted(x["id"] for x in list(books) + list(adventures)
                 if x.get("published", "") >= cutoff and x["id"] not in listed)
    if new:
        out.append(f"in the clone, published on or after {cutoff}, not in sources-2024.json: {', '.join(new)}")
    return out
